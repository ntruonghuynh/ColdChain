"""Citation and response verification against the exact generation evidence set."""

from __future__ import annotations

import json
import re
from datetime import datetime
from collections.abc import Mapping
from typing import Any

from pydantic import ValidationError

from .schemas import ExplanationContent, ExplanationValidationDiagnostics
from .temporal import timestamp_relation


def verify_citations(
    content: ExplanationContent,
    supplied_sources: Mapping[str, str],
    *,
    required_policy_version: str,
    required_sensor_interval: tuple[str, str],
    response_policy_version: str,
    response_sensor_interval: tuple[str, str],
) -> tuple[bool, str | None]:
    if response_policy_version != required_policy_version:
        return False, "policy_version_mismatch"
    if response_sensor_interval != required_sensor_interval:
        return False, "sensor_interval_mismatch"
    if not content.citations:
        return False, "citations_missing"
    for citation in content.citations:
        source = supplied_sources.get(citation.source_id)
        if source is None:
            return False, "source_not_supplied"
        if citation.quote is not None and citation.quote not in source:
            return False, "quote_not_in_source"
    return True, None


def validate_generated_content(
    raw: str,
    supplied_sources: Mapping[str, str],
    *,
    finish_reason: str | None,
    prompt_tokens: int | None,
    completion_tokens: int | None,
    required_policy_version: str,
    required_sensor_interval: tuple[str, str],
    response_policy_version: str,
    response_sensor_interval: tuple[str, str],
    temporal_facts: list[dict[str, Any]] | None = None,
    evidence_cutoff_at: str | None = None,
) -> tuple[ExplanationContent | None, ExplanationValidationDiagnostics]:
    """Validate generated bytes in stages and return only safe diagnostic categories.

    Raw provider text and Pydantic error payloads are intentionally never returned
    or persisted by this helper.
    """
    diagnostics = ExplanationValidationDiagnostics(
        provider_call_status="succeeded",
        provider_finish_reason=finish_reason,
        evidence_validation_status="passed",
        prompt_token_count=prompt_tokens,
        completion_token_count=completion_tokens,
    )
    if finish_reason == "length":
        return None, diagnostics.model_copy(update={
            "application_validation_status": "rejected",
            "output_parse_status": "failed",
            "output_parse_failure_category": "completion_limit_reached",
        })
    try:
        parsed: Any = json.loads(raw)
    except (json.JSONDecodeError, TypeError):
        return None, diagnostics.model_copy(update={
            "application_validation_status": "rejected",
            "output_parse_status": "failed",
            "output_parse_failure_category": "invalid_json",
        })
    diagnostics = diagnostics.model_copy(update={"output_parse_status": "passed"})
    try:
        content = ExplanationContent.model_validate(parsed)
    except ValidationError:
        return None, diagnostics.model_copy(update={
            "application_validation_status": "rejected",
            "output_schema_status": "failed",
            "output_schema_failure_category": "schema_validation_failed",
        })
    diagnostics = diagnostics.model_copy(update={"output_schema_status": "passed"})
    valid, failure = verify_citations(
        content, supplied_sources,
        required_policy_version=required_policy_version,
        required_sensor_interval=required_sensor_interval,
        response_policy_version=response_policy_version,
        response_sensor_interval=response_sensor_interval,
    )
    if not valid:
        return None, diagnostics.model_copy(update={
            "application_validation_status": "rejected",
            "citation_validation_status": "failed",
            "citation_failure_category": failure,
        })
    temporal_valid, temporal_failure = verify_temporal_claims(
        content, temporal_facts or [], evidence_cutoff_at=evidence_cutoff_at
    )
    if not temporal_valid:
        return None, diagnostics.model_copy(update={
            "application_validation_status": "rejected",
            "citation_validation_status": "passed",
            "temporal_validation_status": "failed",
            "temporal_failure_category": temporal_failure,
        })
    return content, diagnostics.model_copy(update={
        "application_validation_status": "passed",
        "citation_validation_status": "passed",
        "temporal_validation_status": "passed",
    })


def verify_temporal_claims(
    content: ExplanationContent,
    temporal_facts: list[dict[str, Any]],
    *,
    evidence_cutoff_at: str | None,
) -> tuple[bool, str | None]:
    """Check explicit claims and provable cutoff contradictions; not full NL verification."""
    facts = {(f.get("evidence_ref"), f.get("timestamp_field"), f.get("timestamp")): f
             for f in temporal_facts}
    for claim in content.temporal_claims:
        fact = facts.get((claim.evidence_ref, claim.timestamp_field, claim.timestamp))
        if fact is None or claim.relation_to_cutoff != fact.get("relation_to_cutoff"):
            return False, "temporal_fact_mismatch"
        expected = fact.get("relation_to_cutoff")
        text = claim.statement_vi.casefold()
        if expected in {"before", "at", "after"}:
            contradicts = (
                (expected in {"before", "at"} and re.search(r"\b(after|later than)\s+(?:the\s+)?cutoff\b|sau\s+(?:mốc\s+)?cutoff", text))
                or (expected == "after" and re.search(r"\b(before|earlier than)\s+(?:the\s+)?cutoff\b|trước\s+(?:mốc\s+)?cutoff", text))
            )
            if contradicts:
                return False, "temporal_cutoff_contradiction"
    # Also detect a date explicitly tied to cutoff in any output prose, even if
    # the model omitted the structured claim. This is intentionally narrow.
    prose = " ".join([content.summary_vi, *content.observations_vi, *content.policy_findings_vi,
                      *content.ml_advisories_vi, *content.potential_factors_vi,
                      *content.recommended_steps_vi, *content.unknowns_vi])
    if evidence_cutoff_at:
        lowered_prose = prose.casefold()
        cutoff_ref = datetime.fromisoformat(evidence_cutoff_at.replace("Z", "+00:00"))
        after_cutoff = re.compile(
            r"(?:\bafter\b|\blater than\b|\bsau\b)\s+(?:the\s+)?(?:evidence\s+)?cutoff"
        )
        before_cutoff = re.compile(
            r"(?:\bbefore\b|\bearlier than\b|\btrước\b)\s+(?:the\s+)?(?:evidence\s+)?cutoff"
        )
        for fact in temporal_facts:
            value = fact.get("timestamp")
            if not isinstance(value, str) or not value:
                continue
            timestamp_forms = {value.casefold(), value[:10].casefold()}
            for timestamp_text in timestamp_forms:
                position = lowered_prose.find(timestamp_text)
                if position < 0:
                    continue
                local_text = lowered_prose[max(0, position - 120): position + len(timestamp_text) + 120]
                relation = timestamp_relation(value, cutoff_ref)
                if relation in {"before", "at"} and after_cutoff.search(local_text):
                    return False, "temporal_cutoff_contradiction"
                if relation == "after" and before_cutoff.search(local_text):
                    return False, "temporal_cutoff_contradiction"
    return True, None

